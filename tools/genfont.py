#!/usr/bin/env python3
"""Builds src/font_data.c (or --out) for a language (--lang, default tr) from assets/fonts.spec: 2-bit antialiased glyphs, subset by usage.

A spec line is `size weight characters`. The token @strings stands for every character found in the
string literals of the user interface sources, so a new string never needs a manual font change."""
import os
import re
import sys
from PIL import Image, ImageDraw, ImageFont

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
fonts = {
    "regular": os.path.join(root, "third_party/inter/Inter-Regular.otf"),
    "medium": os.path.join(root, "third_party/inter/Inter-Medium.otf"),
}

LANG = "tr"
OUT = "src/font_data.c"
args = sys.argv[1:]
while args:
    opt = args.pop(0)
    if opt == "--lang":
        LANG = args.pop(0)
    elif opt == "--out":
        OUT = args.pop(0)
    else:
        sys.exit("usage: genfont.py [--lang code] [--out file]")

CJK_FONTS = {
    "zh": "third_party/noto-cjk/NotoSansCJKsc-Regular.otf",
    "ja": "third_party/noto-cjk/NotoSansCJKjp-Regular.otf",
    "ko": "third_party/noto-cjk/NotoSansCJKkr-Regular.otf",
}

STRING_SOURCES = ["src/lang/%s.h" % LANG, "src/fmt.c", "src/ui_boot.c", "src/screens.c", "src/screens2.c", "src/ui.c", "canary/canary_b.c", "canary/canary_c.c", "canary/canary_f.c", "canary/canary_g.c"]


def used_chars():  # noqa
    chars = set()
    pattern = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
    for rel in STRING_SOURCES:
        path = os.path.join(root, rel)
        if not os.path.exists(path):
            continue
        text = open(path, encoding="utf-8").read()
        for m in pattern.finditer(text):
            s = m.group(1)
            s = s.replace("\\\\", "\x00")
            s = re.sub(r"\\x([0-9A-Fa-f]{2})", lambda mm: bytes([int(mm.group(1), 16)]).decode("latin-1"), s)
            s = re.sub(r"\\[nrt\"']", "", s).replace("\x00", "\\")
            # a UTF-8 sequence written as \xC2\xB7 comes out as two latin-1 characters: decode it back
            try:
                s = s.encode("latin-1").decode("utf-8")
            except (UnicodeEncodeError, UnicodeDecodeError):
                pass
            chars.update(s)
    return chars


STRINGS = used_chars()


def title_chars():
    """characters of the strings that are drawn in the 20 point font: screen titles, alarm levels, guide page titles, profile names"""
    text = open(os.path.join(root, "src/lang/%s.h" % LANG), encoding="utf-8").read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    chars = set()
    string = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
    for m in re.finditer(r"^#define\s+(S_T_\w+|S_P_\w+|S_NORMAL|S_ATTENTION|S_DANGER|S_EVACUATE|S_CLOCK_DATE)\s+(.*)$", text, flags=re.M):
        for lit in string.findall(m.group(2)):
            chars.update(lit)
    guide = re.search(r"^#define GUIDE_DATA.*?^\}", text, flags=re.M | re.S)
    if guide:
        for m in re.finditer(r'^\s{4}\{"((?:[^"\\]|\\.)*)"', guide.group(0), flags=re.M):
            chars.update(m.group(1))
    return chars


TITLES = title_chars()

specs = []
for line in open(os.path.join(root, "assets/fonts.spec"), encoding="utf-8"):
    line = line.rstrip("\n")
    if not line.strip() or line.startswith("#"):
        continue
    size, weight, spec = line.split(None, 2)
    chars = set()
    for token in spec.split():
        if token == "@strings":
            chars |= STRINGS
        elif token == "@titles":
            chars |= TITLES
        else:
            chars |= set(token)
    specs.append((int(size), weight, sorted(chars | {" "})))

out = ['/* Generated by tools/genfont.py from assets/fonts.spec. Do not edit. */',
       '#include "font.h"', '']

total = 0
done = {}
for size, weight, chars in specs:
    face = ImageFont.truetype(fonts[weight], size)
    cjk = ImageFont.truetype(os.path.join(root, CJK_FONTS[LANG]), size) if LANG in CJK_FONTS else None
    ascent, descent = face.getmetrics()
    glyphs, blob = [], bytearray()
    name = f"font_{size}_{weight}"
    if cjk and size == 14 and weight == "medium" and (12, "regular") in done and done[(12, "regular")][0] == chars:
        # the body text of these scripts is drawn in the 12 pixel glyphs in every slot: it saves a whole bitmap set
        reg = "font_12_regular"
        out.append(f"const font_t {name} = {{{reg}_glyphs, {done[(12, 'regular')][1]}, {reg}_bits, {done[(12, 'regular')][2]}, {done[(12, 'regular')][3]}}};")
        out.append("")
        print(f"{name}: shares the glyphs of {reg}", file=sys.stderr)
        continue
    if cjk and weight == "medium" and (size, "regular") in done and done[(size, "regular")][0] == chars:
        # one weight only for these scripts: the medium font is the regular one
        reg = f"font_{size}_regular"
        out.append(f"const font_t {name} = {{{reg}_glyphs, {done[(size, 'regular')][1]}, {reg}_bits, {ascent}, {ascent + descent}}};")
        out.append("")
        print(f"{name}: shares the glyphs of {reg}", file=sys.stderr)
        continue
    for ch in chars:
        face_of = cjk if (cjk and ord(ch) >= 0x2E80) else face
        # a glyph larger than its line box would be cut: use the face metrics of the character
        face_use = face_of
        adv = round(face_use.getlength(ch))
        l, t, r, b = face_use.getbbox(ch, anchor="ls")
        w, h = max(r - l, 0), max(b - t, 0)
        off = len(blob)
        if ch != " " and w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=face_use, fill=255, anchor="ls")
            px = [min(3, (a + 42) // 85) for a in img.tobytes()]
            for i in range(0, len(px), 4):
                q = px[i:i + 4] + [0] * (4 - len(px[i:i + 4]))
                blob.append(q[0] << 6 | q[1] << 4 | q[2] << 2 | q[3])
        else:
            w = h = 0
        glyphs.append((ord(ch), adv, w, h, l, -t, off))
    done[(size, weight)] = (chars, len(glyphs), ascent, ascent + descent)
    out.append(f"static const uint8_t {name}_bits[] = {{")
    for i in range(0, len(blob), 16):
        out.append("    " + ",".join(f"0x{v:02x}" for v in blob[i:i + 16]) + ",")
    if not blob:
        out.append("    0,")
    out.append("};")
    out.append(f"static const glyph_t {name}_glyphs[] = {{")
    for g in glyphs:
        out.append("    {%d,%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append(f"const font_t {name} = {{{name}_glyphs, {len(glyphs)}, {name}_bits, {ascent}, {ascent + descent}}};")
    out.append("")
    total += len(blob) + 10 * len(glyphs)
    print(f"{name}: {len(glyphs)} glyphs, {len(blob)} bytes bitmap, line height {ascent + descent}", file=sys.stderr)

target = os.path.join(root, OUT)
os.makedirs(os.path.dirname(target), exist_ok=True)
open(target, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(f"font data about {total} bytes ({len(STRINGS)} distinct characters in strings)", file=sys.stderr)
